/**
 * Build-time only: emits src/fr-poc/registry.prod.generated.ts with imports for
 * published FR guides only (parsed from registry.ts). Unpublished modules never
 * appear in this file, so they do not enter the production client bundle.
 *
 * Optional: FR_PROD_ROUTE_FIXTURE — JSON array of { "id": string, "published": boolean }
 * overrides parsed `published` flags (for validation/tests without editing registry).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { EN_TO_FR_BLOG_PATH } from "./data/fr-en-blog-paths.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const registryPath = path.join(root, "src/fr-poc/registry.ts");
const outRegistryPath = path.join(root, "src/fr-poc/registry.prod.generated.ts");
const outPickPath = path.join(root, "src/fr-poc/extraRoutes.prod.pick.ts");
const outPublishingPath = path.join(root, "src/fr-poc/frPublishing.generated.ts");

// Order must match registry.ts object shape: id → slug → path → published → content
const ENTRY_RE =
  /\{\s*id:\s*"([^"]+)"[\s\S]*?slug:\s*"([^"]+)"[\s\S]*?path:\s*"(\/fr\/blog\/[^"]+)"[\s\S]*?published:\s*(true|false)[\s\S]*?content:\s*(\w+),/g;

function parseRegistry(source) {
  const rows = [];
  let m;
  ENTRY_RE.lastIndex = 0;
  while ((m = ENTRY_RE.exec(source)) !== null) {
    rows.push({
      id: m[1],
      slug: m[2],
      path: m[3],
      published: m[4] === "true",
      contentExport: m[5],
    });
  }
  return rows;
}

/** Real Vercel production builds must not ship fixture overrides baked into generated TS. */
if (process.env.VERCEL === "1" && process.env.FR_PROD_ROUTE_FIXTURE?.trim()) {
  console.error(
    "generate-fr-registry-prod: FR_PROD_ROUTE_FIXTURE is set on Vercel — remove it from project/env for release builds",
  );
  process.exit(1);
}

let fixtureOverrides = [];
if (process.env.FR_PROD_ROUTE_FIXTURE?.trim()) {
  try {
    fixtureOverrides = JSON.parse(process.env.FR_PROD_ROUTE_FIXTURE);
  } catch (e) {
    console.error("FR_PROD_ROUTE_FIXTURE must be valid JSON array");
    process.exit(1);
  }
}

const fixtureMap = new Map(
  fixtureOverrides.map((o) => [o.id, o.published === true]),
);

const source = fs.readFileSync(registryPath, "utf8");
let rows = parseRegistry(source);

if (rows.length === 0) {
  console.error("generate-fr-registry-prod: no registry rows parsed from registry.ts");
  process.exit(1);
}

rows = rows.map((r) => {
  if (fixtureMap.has(r.id)) {
    return { ...r, published: fixtureMap.get(r.id) };
  }
  return r;
});

const published = rows.filter((r) => r.published);

const importLines =
  published.length === 0
    ? []
    : published.map((r) => `import { ${r.contentExport} } from "./content/${r.id}.fr";`);

const recordLines = published.map((r) =>
  [
    "  {",
    `    id: "${r.id}",`,
    `    locale: "fr" as const,`,
    `    slug: "${r.slug}",`,
    `    path: "${r.path}",`,
    `    published: true,`,
    `    content: ${r.contentExport},`,
    "  },",
  ].join("\n"),
);

const importBlock = importLines.length ? `${importLines.join("\n")}\n\n` : "";
const recordsInner = recordLines.length ? `${recordLines.join("\n")}\n` : "";

const fileBody = `// AUTO-GENERATED by scripts/generate-fr-registry-prod.mjs — do not edit
import type { LocalizedGuideRegistryEntry } from "../content/guides/types";
${importBlock}export const FR_PROD_REGISTRY: readonly LocalizedGuideRegistryEntry[] = [
${recordsInner}];
`;

fs.writeFileSync(outRegistryPath, fileBody, "utf8");

const pickBody =
  published.length === 0
    ? `// AUTO-GENERATED by scripts/generate-fr-registry-prod.mjs — do not edit
export { frPocRouteElement } from "./extraRoutes.prod.empty";
`
    : `// AUTO-GENERATED by scripts/generate-fr-registry-prod.mjs — do not edit
export { frPocRouteElement } from "./extraRoutes.prod.routes";
`;
fs.writeFileSync(outPickPath, pickBody, "utf8");

const enByFrPath = new Map(Object.entries(EN_TO_FR_BLOG_PATH).map(([en, fr]) => [fr, en]));
const publishedFrPaths = published.map((r) => r.path);
const publishedEnPaths = publishedFrPaths.map((fr) => enByFrPath.get(fr)).filter(Boolean);

const enToFrJson = JSON.stringify(EN_TO_FR_BLOG_PATH, null, 2);

const publishingBody = `// AUTO-GENERATED by scripts/generate-fr-registry-prod.mjs — do not edit
import type { HreflangAlternate } from "../lib/pageSeoHead";
import type { PageSeoHeadOptions } from "../lib/pageSeoHead";
import { FR_BLOG_HUB_PATH } from "./frSiteChrome";

export const EN_TO_FR_BLOG_PATH: Readonly<Record<string, string>> = ${enToFrJson};

export const FR_PUBLISHED_FR_PATHS = new Set<string>([${publishedFrPaths.map((p) => `"${p}"`).join(", ")}]);

export const FR_PUBLISHED_EN_PATHS = new Set<string>([${publishedEnPaths.map((p) => `"${p}"`).join(", ")}]);

const FR_TO_EN: Map<string, string> = new Map(
  Object.entries(EN_TO_FR_BLOG_PATH).map(([en, fr]) => [fr, en]),
);

/** Production / prerender: reciprocal hreflang for FR pages (published only). */
export function mergeFrAlternatesForSsg(seo: PageSeoHeadOptions): PageSeoHeadOptions {
  const frPath = seo.path;
  if (frPath === FR_BLOG_HUB_PATH) {
    if (FR_PUBLISHED_FR_PATHS.size === 0) return seo;
    return {
      ...seo,
      alternates: [
        { hreflang: "en", path: "/blog" },
        { hreflang: "fr", path: FR_BLOG_HUB_PATH },
        { hreflang: "x-default", path: "/blog" },
      ],
    };
  }
  if (!frPath.startsWith("/fr/blog/")) return seo;
  if (!FR_PUBLISHED_FR_PATHS.has(frPath)) return seo;
  const en = FR_TO_EN.get(frPath);
  if (!en) return seo;
  return {
    ...seo,
    alternates: [
      { hreflang: "en", path: en },
      { hreflang: "fr", path: frPath },
      { hreflang: "x-default", path: en },
    ],
  };
}

/** EN /blog/:slug — reciprocal hreflang when the French translation is published. */
export function enBlogAlternatesWhenFrPublished(enPath: string): readonly HreflangAlternate[] | undefined {
  const fr = EN_TO_FR_BLOG_PATH[enPath];
  if (!fr || !FR_PUBLISHED_FR_PATHS.has(fr)) return undefined;
  return [
    { hreflang: "en", path: enPath },
    { hreflang: "fr", path: fr },
    { hreflang: "x-default", path: enPath },
  ];
}

/** EN /blog hub — hreflang when at least one FR guide is published. */
export function blogHubAlternates(): readonly HreflangAlternate[] | undefined {
  if (FR_PUBLISHED_FR_PATHS.size === 0) return undefined;
  return [
    { hreflang: "en", path: "/blog" },
    { hreflang: "fr", path: FR_BLOG_HUB_PATH },
    { hreflang: "x-default", path: "/blog" },
  ];
}

/** Production client: resolve markdown and structured internal guide links on FR pages. */
export function resolveFrGuideInternalHrefProd(href: string): string {
  if (href.startsWith("/blog/")) {
    const fr = EN_TO_FR_BLOG_PATH[href];
    if (fr && FR_PUBLISHED_FR_PATHS.has(fr)) return fr;
    return href;
  }
  if (href.startsWith("/fr/blog/")) {
    if (FR_PUBLISHED_FR_PATHS.has(href)) return href;
    const en = FR_TO_EN.get(href);
    return en ?? href;
  }
  return href;
}
`;

fs.writeFileSync(outPublishingPath, publishingBody, "utf8");

console.log(
  `generate-fr-registry-prod: ${published.length} published module(s) → registry.prod.generated.ts + extraRoutes.prod.pick.ts + frPublishing.generated.ts`,
);
